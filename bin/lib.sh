# bin/lib.sh: helpers shared by install.sh, bin/kit, and adapters/*.sh.
# Sourced, never executed. Callers set KIT_DIR before sourcing.
# Every change to HOME goes through these functions so that --dry-run,
# backups, and uninstall behave the same for every adapter.

KIT_VERSION=$(cat "$KIT_DIR/VERSION")
GENERATED_MARK="Generated by agent-kit"
DRY_RUN=${DRY_RUN:-0}
BACKUP_ROOT=$HOME/.agent-kit-backup
BACKUP_DIR=$BACKUP_ROOT/$(date +%Y%m%d-%H%M%S)

say() { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }

# act <description> <command...>: run a change, or only print it in dry-run mode.
act() {
  local desc=$1
  shift
  if [ "$DRY_RUN" = 1 ]; then
    say "[dry-run] $desc"
  else
    say "$desc"
    "$@"
  fi
}

# generated_header <source>: one-line header for files the kit generates.
generated_header() { printf '%s %s from %s. Do not edit.' "$GENERATED_MARK" "$KIT_VERSION" "$1"; }

is_generated() { [ -f "$1" ] && head -n 3 "$1" | grep -q "$GENERATED_MARK"; }

# is_kit_link <path>: true if path is a symlink pointing into this kit.
is_kit_link() {
  [ -L "$1" ] || return 1
  case "$(readlink "$1")" in "$KIT_DIR"/*) return 0 ;; esac
  return 1
}

_mkparent() { mkdir -p "$(dirname "$1")"; }
_move_to_backup() { _mkparent "$BACKUP_DIR/$2" && mv "$1" "$BACKUP_DIR/$2"; }
_copy_to_backup() { _mkparent "$BACKUP_DIR/$2" && cp -p "$1" "$BACKUP_DIR/$2"; }
_link_now() { _mkparent "$2" && ln -s "$1" "$2"; }
_write_now() { _mkparent "$2" && cat "$1" > "$2"; }

# backup <path>: move an existing file, directory, or foreign link out of the way.
backup() {
  { [ -e "$1" ] || [ -L "$1" ]; } || return 0
  local rel=${1#"$HOME"/}
  act "backup $1 -> $BACKUP_DIR/$rel" _move_to_backup "$1" "$rel"
}

# link <source in kit> <destination>: per-item symlink, backing up whatever was there.
link() {
  local src=$1 dest=$2
  [ -L "$dest" ] && [ "$(readlink "$dest")" = "$src" ] && return 0
  if is_kit_link "$dest"; then
    act "remove old kit link $dest" rm "$dest"
  else
    backup "$dest"
  fi
  act "link $dest -> $src" _link_now "$src" "$dest"
}

# unlink_kit <path>: remove it only if it is a link into this kit.
unlink_kit() {
  is_kit_link "$1" || return 0
  act "remove link $1" rm "$1"
}

# unlink_all_kit <dir> [dangling]: remove links into the kit directly inside dir;
# with "dangling", only those whose target no longer exists (items removed from the kit).
unlink_all_kit() {
  [ -d "$1" ] || return 0
  local p
  for p in "$1"/* "$1"/.[!.]*; do
    is_kit_link "$p" || continue
    [ "${2:-}" = dangling ] && [ -e "$p" ] && continue
    act "remove link $p" rm "$p"
  done
}

# write_file <content file> <destination>: write if changed; back up files the kit did not generate.
write_file() {
  local src=$1 dest=$2
  [ -f "$dest" ] && [ ! -L "$dest" ] && cmp -s "$src" "$dest" && return 0
  is_generated "$dest" || backup "$dest"
  act "write $dest" _write_now "$src" "$dest"
}

# remove_generated_in <dir> <glob>: delete files the kit generated, never others.
remove_generated_in() {
  [ -d "$1" ] || return 0
  local p
  for p in "$1"/$2; do
    is_generated "$p" && act "remove generated $p" rm "$p"
  done
  return 0
}

# remove_empty_dirs <dir...>: after uninstall, drop directories the install left empty.
# An empty directory holds no user data, so removing one the user had is harmless.
remove_empty_dirs() {
  [ "$DRY_RUN" = 1 ] && return 0
  local d
  for d in "$@"; do
    rmdir "$d" 2>/dev/null || true
  done
}

_has_backup() {
  local d
  for d in "$BACKUP_ROOT"/*/; do
    [ -e "$d$1" ] && return 0
  done
  return 1
}

# json_edit <file> <jq filter> [jq args...]: apply a filter to a JSON file (missing = {}).
# The first time the kit changes a file, a copy of the original goes to the backup.
# A result of {} removes the file; restore_backups brings back an original if there was one.
json_edit() {
  local file=$1 filter=$2 tmp rel
  shift 2
  rel=${file#"$HOME"/}
  tmp=$(mktemp)
  if ! { [ -f "$file" ] && cat "$file" || echo '{}'; } | jq "$@" "$filter" > "$tmp"; then
    rm -f "$tmp"
    warn "cannot parse $file, left unchanged"
    return 1
  fi
  if [ "$(jq -c . "$tmp")" = '{}' ]; then
    [ -f "$file" ] && act "remove $file (nothing left but kit entries)" rm "$file"
  elif ! { [ -f "$file" ] && cmp -s "$tmp" "$file"; }; then
    if [ -f "$file" ] && ! _has_backup "$rel"; then
      act "backup copy $file -> $BACKUP_DIR/$rel" _copy_to_backup "$file" "$rel"
    fi
    act "update $file" _write_now "$tmp" "$file"
  fi
  rm -f "$tmp"
}

_same_content() {
  cmp -s "$1" "$2" && return 0
  case "$1" in *.json) [ "$(jq -S -c . "$1" 2>/dev/null)" = "$(jq -S -c . "$2" 2>/dev/null)" ] ;; *) return 1 ;; esac
}

# restore_backups: after uninstall, put every backed-up original back where
# nothing else took its place. Backups whose destination changed are kept.
restore_backups() {
  [ -d "$BACKUP_ROOT" ] || return 0
  if [ "$DRY_RUN" = 1 ]; then
    say "[dry-run] restore backups from $BACKUP_ROOT"
    return 0
  fi
  local d rel dest
  for d in "$BACKUP_ROOT"/*/; do
    [ -d "$d" ] || continue
    (cd "$d" && find . -type f -o -type l) | while IFS= read -r rel; do
      rel=${rel#./}
      dest=$HOME/$rel
      if [ ! -e "$dest" ] && [ ! -L "$dest" ]; then
        say "restore $dest"
        _mkparent "$dest" && mv "$d$rel" "$dest"
      elif _same_content "$d$rel" "$dest"; then
        say "restore $dest"
        rm -f "$dest" && mv "$d$rel" "$dest"
      else
        warn "kept backup $d$rel: $dest has changed since"
      fi
    done
    find "$d" -depth -type d -empty -exec rmdir {} \;
  done
  rmdir "$BACKUP_ROOT" 2>/dev/null || true
}
